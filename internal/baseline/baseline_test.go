func TestJSONSnapshot_AbsoluteAndRelativePathsMatch(t *testing.T) {
	t.Chdir(t.TempDir())
	abs, err := filepath.Abs(".gitlab-ci.yml")
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct{ saved, current string }{
		{abs, ".gitlab-ci.yml"}, // snapshots written before #835
		{".gitlab-ci.yml", abs}, // relative reports with absolute CLI arguments
	} {
		data, err := json.Marshal(map[string]any{"findings": []map[string]string{{"rule": "GL001", "file": tc.saved, "message": "mutable image"}}})
		if err != nil {
			t.Fatal(err)
		}
		b, err := Load(write(t, string(data)))
		if err != nil {
			t.Fatal(err)
		}
		if !b.IsNew(finding.Finding{RuleID: "GL001", File: "other.yml", Message: "mutable image"}) {
			t.Error("a different file matched the snapshot")
		}
		if b.IsNew(finding.Finding{RuleID: "GL001", File: tc.current, Message: "mutable image"}) {
			t.Errorf("snapshot path %q did not match %q", tc.saved, tc.current)
		}
	}
}

func write(t *testing.T, content string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), "baseline")
	if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
	return p
}

func gl001(line int) finding.Finding {
	return finding.Finding{RuleID: "GL001", File: ".gitlab-ci.yml", Line: line, Message: `image "node:latest" uses mutable tag`}
}

func TestJSONSnapshot_MatchesByMessageIgnoringLine(t *testing.T) {
	p := write(t, `{"findings":[{"rule":"GL001","file":".gitlab-ci.yml","line":5,"message":"image \"node:latest\" uses mutable tag"}]}`)
	b, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	// Same finding, drifted to a different line — must NOT be reported as new.
	if b.IsNew(gl001(12)) {
		t.Fatal("drifted baseline finding reported as new")
	}
}

func TestJSONSnapshot_DifferentMessageIsNew(t *testing.T) {
	p := write(t, `{"findings":[{"rule":"GL001","file":".gitlab-ci.yml","line":5,"message":"image \"node:latest\" uses mutable tag"}]}`)
	b, _ := Load(p)
	other := finding.Finding{RuleID: "GL001", File: ".gitlab-ci.yml", Line: 9, Message: `image "python:latest" uses mutable tag`}
	if !b.IsNew(other) {
		t.Fatal("finding with a different message should be new")
	}
}

func TestMultiplicity(t *testing.T) {
	p := write(t, `{"findings":[{"rule":"GL001","file":".gitlab-ci.yml","line":5,"message":"image \"node:latest\" uses mutable tag"}]}`)
	b, _ := Load(p)
	// One accepted occurrence absorbs the first; a second identical finding is new.
	if b.IsNew(gl001(5)) {
		t.Fatal("first occurrence should match baseline")
	}
	if !b.IsNew(gl001(5)) {
		t.Fatal("second identical occurrence should be new (count exhausted)")
	}
}

func TestIgnoreFileFormat_MatchesByRuleAndFile(t *testing.T) {
	p := write(t, "# Generated by glsec --generate-ignore\n.gitlab-ci.yml:5 GL001\n")
	b, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	// No message available in .glsec-ignore, so match is rule+file, drift-tolerant.
	if b.IsNew(gl001(99)) {
		t.Fatal("baselined finding reported as new")
	}
	if !b.IsNew(finding.Finding{RuleID: "GL003", File: ".gitlab-ci.yml", Line: 5}) {
		t.Fatal("different rule should be new")
	}
}

func TestEmpty(t *testing.T) {
	if !Empty().IsNew(gl001(1)) {
		t.Fatal("empty baseline must report everything as new")
	}
}

func TestLoad_MissingFile(t *testing.T) {
	_, err := Load(filepath.Join(t.TempDir(), "absent"))
	if !os.IsNotExist(err) {
		t.Errorf("got %v, want a not-exist error", err)
	}
}

func TestLoad_InvalidJSON(t *testing.T) {
	if _, err := Load(write(t, `{"findings": [`)); err == nil {
		t.Error("a truncated JSON snapshot must fail to load, not become an empty baseline")
	}
}

// Reports mask secrets (#831): a snapshot written before that, or with
// --no-redact, and one written now both match the same finding.
func TestJSONSnapshot_MaskedAndUnmaskedMessagesMatch(t *testing.T) {
	raw := "pipes https://u:" + "pw12345678" + "@example.com into bash"
	masked := "pipes https://u:" + "**********" + "@example.com into bash"
	for _, snapMsg := range []string{raw, masked} {
		data, err := json.Marshal(map[string]any{"findings": []map[string]any{{"rule": "GL011", "file": "ci.yml", "message": snapMsg}}})
		if err != nil {
			t.Fatal(err)
		}
		b, err := loadJSON(data)
		if err != nil {
			t.Fatal(err)
		}
		if b.IsNew(finding.Finding{RuleID: "GL011", File: "ci.yml", Message: raw}) {
			t.Errorf("snapshot message %q should match the finding", snapMsg)
		}
	}
}
